use std::fmt;

#[derive(Clone, Copy, Debug, Eq, PartialEq)]
pub struct EmptyName;
impl fmt::Display for EmptyName {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        f.write_str("SMT-LIB name must not be empty")
    }
}
impl std::error::Error for EmptyName {}

/// Sanitizes names according to the pinned Silicon SMT-LIB/Z3/cvc5 list.
#[derive(Clone, Copy, Debug, Default)]
pub struct SmtlibNameSanitizer;
impl SmtlibNameSanitizer {
    pub fn sanitize(&self, name: &str) -> Result<String, EmptyName> {
        if name.is_empty() {
            return Err(EmptyName);
        }
        let mut result = String::new();
        // Scala iterates UTF-16 Char values: a supplementary character produces
        // two fallback characters, not one Unicode-scalar replacement.
        for (index, unit) in name.encode_utf16().enumerate() {
            let character = char::from_u32(u32::from(unit)).unwrap_or('\u{fffd}');
            let allowed = character.is_ascii_alphabetic()
                || matches!(character, '_' | '$' | '@' | '%' | '<' | '>' | '~')
                || (index > 0 && (character.is_ascii_digit() || character == '.'));
            if allowed {
                result.push(character);
            } else {
                result.push(match character {
                    '#' => '%',
                    '[' => '<',
                    ']' => '>',
                    ',' => '~',
                    ':' | ' ' => '_',
                    _ => '_',
                });
            }
        }
        while RESERVED_NAMES.contains(&result.as_str()) {
            result.push('_');
        }
        Ok(result)
    }
}

